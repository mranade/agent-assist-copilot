#!/usr/bin/env python3
"""Evaluate the assist agent.

Two sets, kept separate on purpose:

* data/eval/utterances.jsonl: held-out customer lines written before the
  retrieval thresholds and synonym list were set. This is the honest number.
* data/calls/calls.json: the three demo calls. The thresholds were chosen by
  looking at these, so they measure "does the demo behave as designed",
  not generalization.

For every line we check the end-to-end outcome, not just retrieval:
in-scope lines should produce a suggestion that includes an expected
article; out-of-scope lines should escalate; small talk should be skipped.

Usage:
    python scripts/run_eval.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from assist.agent import AssistAgent  # noqa: E402
from assist.retriever import TfidfRetriever  # noqa: E402
from assist.steps import CallState  # noqa: E402
from assist.suggest import ExtractiveSuggester  # noqa: E402


def expected_outcome(item: dict) -> str:
    if item.get("small_talk"):
        return "skipped"
    return "escalated" if item.get("expected_kb") is None else "suggested"


def judge(item: dict, result, hits_top3: list[str]) -> dict:
    want = expected_outcome(item)
    shown = [a.kb_id for a in result.suggestion.articles] if result.suggestion and result.outcome == "suggested" else []
    exp = item.get("expected_kb") or []
    if want == "suggested":
        correct = result.outcome == "suggested" and any(k in shown for k in exp)
    else:
        correct = result.outcome == want
    return {
        "text": item["text"], "want": want, "got": result.outcome,
        "expected_kb": exp, "shown": shown, "top3": hits_top3,
        "retrieval_hit": bool(exp) and any(k in hits_top3 for k in exp),
        "correct": correct,
    }


def main() -> None:
    retriever = TfidfRetriever.from_kb(ROOT / "data" / "kb")
    agent = AssistAgent(retriever, ExtractiveSuggester())

    held_out = [
        json.loads(line)
        for line in (ROOT / "data" / "eval" / "utterances.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    held_rows = []
    for item in held_out:
        top3 = list(dict.fromkeys(h.chunk.kb_id for h in retriever.search(item["text"], k=6)))[:3]
        held_rows.append(judge(item, agent.on_customer_turn(item["text"]), top3))

    # Demo calls are played in full, agent turns included, so the active issue
    # and checklist progress carry across turns the way they do in the app.
    call_rows = []
    for call in json.loads((ROOT / "data" / "calls" / "calls.json").read_text(encoding="utf-8")):
        state = CallState()
        for turn in call["turns"]:
            result = agent.on_turn(turn["speaker"], turn["text"], state)
            if turn["speaker"] != "customer":
                continue
            item = {
                "text": turn["text"],
                "expected_kb": turn.get("expected_kb"),
                "small_talk": "expected_kb" not in turn or (turn.get("expected_kb") is None and not turn.get("out_of_scope")),
            }
            top3 = list(dict.fromkeys(h.chunk.kb_id for h in retriever.search(turn["text"], k=6)))[:3]
            call_rows.append(judge(item, result, top3))

    def pct(rows, key="correct"):
        return f"{sum(r[key] for r in rows)}/{len(rows)} ({sum(r[key] for r in rows) / len(rows):.0%})"

    in_scope = [r for r in held_rows if r["want"] == "suggested"]
    out_scope = [r for r in held_rows if r["want"] == "escalated"]
    small = [r for r in held_rows if r["want"] == "skipped"]

    lines = [
        "# Evaluation results",
        "",
        "Generated by `python scripts/run_eval.py`. Extractive mode, no API key.",
        "",
        "## Held-out customer lines (`data/eval/utterances.jsonl`)",
        "",
        f"- In scope, correct suggestion shown: **{pct(in_scope)}**",
        f"- In scope, expected article in retrieval top 3: {pct(in_scope, 'retrieval_hit')}",
        f"- Out of scope, correctly escalated: **{pct(out_scope)}**",
        f"- Small talk, correctly skipped: {pct(small)}",
        f"- Overall: **{pct(held_rows)}**",
        "",
        "| | Customer line | Expected | Outcome | Articles shown |",
        "|---|---|---|---|---|",
    ]
    for r in held_rows:
        exp = ", ".join(r["expected_kb"]) or r["want"]
        lines.append(
            f"| {'✅' if r['correct'] else '❌'} | {r['text']} | {exp} | {r['got']} | {', '.join(r['shown']) or '-'} |"
        )
    lines += [
        "",
        "## Demo calls (`data/calls/calls.json`, customer turns)",
        "",
        "Thresholds were set using these calls, so this checks the demo behaves as designed rather than how well it generalizes.",
        "",
        f"- Correct: **{pct(call_rows)}**",
        "",
    ]
    report = "\n".join(lines) + "\n"
    (ROOT / "data" / "eval" / "results.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
